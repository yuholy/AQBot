import { createServer } from 'node:http';
import { randomUUID } from 'node:crypto';

const port = Number(process.env.AQBOT_EXTERNAL_AGENT_MOCK_PORT || 8788);
const host = process.env.AQBOT_EXTERNAL_AGENT_MOCK_HOST || '127.0.0.1';
const defaultDelayMs = Number(process.env.AQBOT_EXTERNAL_AGENT_MOCK_DELAY_MS || 3500);

const tasks = new Map();

function sendJson(res, statusCode, payload) {
  const body = JSON.stringify(payload, null, 2);
  res.writeHead(statusCode, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(body),
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET,POST,OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization, X-API-Key',
  });
  res.end(body);
}

function sendText(res, statusCode, message) {
  res.writeHead(statusCode, {
    'Content-Type': 'text/plain; charset=utf-8',
    'Content-Length': Buffer.byteLength(message),
    'Access-Control-Allow-Origin': '*',
  });
  res.end(message);
}

async function readJson(req) {
  const chunks = [];
  for await (const chunk of req) {
    chunks.push(chunk);
  }
  const raw = Buffer.concat(chunks).toString('utf8').trim();
  if (!raw) return {};
  return JSON.parse(raw);
}

function normalizeInput(taskEnvelope) {
  const innerTask = taskEnvelope?.task ?? {};
  const protocol = innerTask?.protocol || 'generic_http';
  const originalTask = innerTask?.task ?? innerTask;
  const context = innerTask?.context ?? originalTask?.context ?? {};
  const inputText =
    innerTask?.prompt ||
    innerTask?.input?.text ||
    originalTask?.input?.text ||
    '';
  const title =
    innerTask?.title ||
    originalTask?.title ||
    'Mock external task';

  return {
    protocol,
    title,
    inputText,
    context,
    raw: taskEnvelope,
  };
}

function buildArtifact(taskId, title) {
  const content = [
    '# AQBot Mock Artifact',
    '',
    `taskId: ${taskId}`,
    `title: ${title}`,
    '',
    'This file was generated by the local mock external-agent service.',
  ].join('\n');

  return {
    name: `mock-report-${taskId}.md`,
    mimeType: 'text/markdown',
    dataBase64: Buffer.from(content, 'utf8').toString('base64'),
  };
}

function finalizeTask(task) {
  if (task.status === 'completed' || task.status === 'failed' || task.status === 'cancelled') {
    return task;
  }

  if (Date.now() - task.createdAt < task.delayMs) {
    return task;
  }

  const summary = [
    `Mock ${task.protocol} task completed.`,
    `Title: ${task.title}.`,
    task.inputText ? `Input: ${task.inputText.slice(0, 180)}.` : null,
  ]
    .filter(Boolean)
    .join(' ');

  const response = {
    externalTaskId: task.id,
    status: 'completed',
    summary,
    result: {
      protocol: task.protocol,
      title: task.title,
      content: [
        `This is a mock result for "${task.title}".`,
        task.inputText ? `Original input: ${task.inputText}` : 'No input text was provided.',
        'You can now switch this AQBot connector to a real compatible service.',
      ].join('\n\n'),
      echoContextKeys: Object.keys(task.context || {}),
    },
    artifacts: task.includeArtifact ? [buildArtifact(task.id, task.title)] : [],
  };

  task.status = 'completed';
  task.response = response;
  return task;
}

function getTaskSnapshot(task) {
  finalizeTask(task);
  if (task.status === 'completed' && task.response) {
    return task.response;
  }
  return {
    externalTaskId: task.id,
    status: task.status,
    summary: `Mock ${task.protocol} task is still running`,
  };
}

const server = createServer(async (req, res) => {
  if (!req.url) {
    sendText(res, 400, 'Missing URL');
    return;
  }

  if (req.method === 'OPTIONS') {
    res.writeHead(204, {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET,POST,OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type, Authorization, X-API-Key',
    });
    res.end();
    return;
  }

  const url = new URL(req.url, `http://${req.headers.host || `${host}:${port}`}`);

  if (req.method === 'GET' && url.pathname === '/health') {
    sendJson(res, 200, {
      ok: true,
      service: 'aqbot-external-agent-mock',
      host,
      port,
      taskCount: tasks.size,
    });
    return;
  }

  if (req.method === 'POST' && url.pathname === '/tasks') {
    try {
      const body = await readJson(req);
      const normalized = normalizeInput(body);
      const taskId = randomUUID();
      const delayMs = Number(normalized.context?.mock?.delayMs || defaultDelayMs);
      const includeArtifact = normalized.context?.mock?.includeArtifact !== false;

      const task = {
        id: taskId,
        protocol: normalized.protocol,
        title: normalized.title,
        inputText: normalized.inputText,
        context: normalized.context,
        raw: normalized.raw,
        status: 'running',
        createdAt: Date.now(),
        delayMs: Number.isFinite(delayMs) ? delayMs : defaultDelayMs,
        includeArtifact,
        response: null,
      };
      tasks.set(taskId, task);

      sendJson(res, 202, {
        externalTaskId: taskId,
        status: 'running',
        summary: `Mock ${normalized.protocol} task accepted`,
      });
    } catch (error) {
      sendJson(res, 400, {
        status: 'failed',
        error: error instanceof Error ? error.message : String(error),
      });
    }
    return;
  }

  if (req.method === 'GET' && (url.pathname.startsWith('/tasks/') || url.pathname.startsWith('/results/'))) {
    const taskId = url.pathname.split('/').pop();
    const task = taskId ? tasks.get(taskId) : null;
    if (!task) {
      sendJson(res, 404, {
        status: 'failed',
        error: 'Task not found',
      });
      return;
    }
    sendJson(res, 200, getTaskSnapshot(task));
    return;
  }

  sendJson(res, 404, {
    status: 'failed',
    error: 'Route not found',
  });
});

server.listen(port, host, () => {
  console.log(`[aqbot-mock] listening on http://${host}:${port}`);
  console.log('[aqbot-mock] health: GET /health');
  console.log('[aqbot-mock] dispatch: POST /tasks');
  console.log('[aqbot-mock] status: GET /tasks/:id');
});
